/*
  One-time repair for Logo cashbox collection rows whose KSLINES.SIGN or local
  currency total fields are NULL/zero.

  Logo cashbox balances ignore these rows in some installations. This repair is
  intentionally narrow: cash collection TRCODE only, non-cancelled rows only,
  and only missing balance fields.
  It does not create any new movement and is safe to re-run.
*/

SET NOCOUNT ON;
SET XACT_ABORT ON;

IF COL_LENGTH(N'dbo.LG_003_01_KSLINES', N'SIGN') IS NULL
BEGIN
    RAISERROR('LG_003_01_KSLINES.SIGN column not found; nothing to repair.', 10, 1);
    RETURN;
END;

IF COL_LENGTH(N'dbo.LG_003_01_KSLINES', N'TRCURR') IS NULL
   OR COL_LENGTH(N'dbo.LG_003_01_KSLINES', N'TRRATE') IS NULL
   OR COL_LENGTH(N'dbo.LG_003_01_KSLINES', N'TRNET') IS NULL
   OR COL_LENGTH(N'dbo.LG_003_01_KSLINES', N'REPORTRATE') IS NULL
   OR COL_LENGTH(N'dbo.LG_003_01_KSLINES', N'REPORTNET') IS NULL
BEGIN
    RAISERROR('LG_003_01_KSLINES local currency total columns not found; nothing to repair.', 10, 1);
    RETURN;
END;

BEGIN TRANSACTION;

UPDATE k
   SET SIGN = 0,
       TRCURR = ISNULL(TRCURR, 0),
       TRRATE = CASE WHEN ISNULL(TRRATE, 0) = 0 THEN 1 ELSE TRRATE END,
       TRNET = CASE WHEN ISNULL(TRNET, 0) = 0 THEN ISNULL(AMOUNT, 0) ELSE TRNET END,
       REPORTRATE = CASE WHEN ISNULL(REPORTRATE, 0) = 0 THEN 1 ELSE REPORTRATE END,
       REPORTNET = CASE WHEN ISNULL(REPORTNET, 0) = 0 THEN ISNULL(AMOUNT, 0) ELSE REPORTNET END,
       ACCREF = CASE
           WHEN COL_LENGTH(N'dbo.LG_003_01_KSLINES', N'ACCREF') IS NOT NULL THEN ISNULL(ACCREF, 0)
           ELSE ACCREF
       END,
       CENTERREF = CASE
           WHEN COL_LENGTH(N'dbo.LG_003_01_KSLINES', N'CENTERREF') IS NOT NULL THEN ISNULL(CENTERREF, 0)
           ELSE CENTERREF
       END,
       CASHACCREF = CASE
           WHEN COL_LENGTH(N'dbo.LG_003_01_KSLINES', N'CASHACCREF') IS NOT NULL THEN ISNULL(CASHACCREF, 0)
           ELSE CASHACCREF
       END,
       CASHCENREF = CASE
           WHEN COL_LENGTH(N'dbo.LG_003_01_KSLINES', N'CASHCENREF') IS NOT NULL THEN ISNULL(CASHCENREF, 0)
           ELSE CASHCENREF
       END,
       ACCFICHEREF = CASE
           WHEN COL_LENGTH(N'dbo.LG_003_01_KSLINES', N'ACCFICHEREF') IS NOT NULL THEN ISNULL(ACCFICHEREF, 0)
           ELSE ACCFICHEREF
       END,
       ACCOUNTED = CASE
           WHEN COL_LENGTH(N'dbo.LG_003_01_KSLINES', N'ACCOUNTED') IS NOT NULL THEN ISNULL(ACCOUNTED, 0)
           ELSE ACCOUNTED
       END,
       REFLECTED = CASE
           WHEN COL_LENGTH(N'dbo.LG_003_01_KSLINES', N'REFLECTED') IS NOT NULL THEN ISNULL(REFLECTED, 0)
           ELSE REFLECTED
       END,
       STATUS = CASE
           WHEN COL_LENGTH(N'dbo.LG_003_01_KSLINES', N'STATUS') IS NOT NULL THEN ISNULL(STATUS, 0)
           ELSE STATUS
       END,
       AFFECTRISK = CASE
           WHEN COL_LENGTH(N'dbo.LG_003_01_KSLINES', N'AFFECTRISK') IS NOT NULL THEN ISNULL(AFFECTRISK, 0)
           ELSE AFFECTRISK
       END,
       BRANCH = CASE
           WHEN COL_LENGTH(N'dbo.LG_003_01_KSLINES', N'BRANCH') IS NOT NULL THEN ISNULL(BRANCH, 0)
           ELSE BRANCH
       END,
       DEPARTMENT = CASE
           WHEN COL_LENGTH(N'dbo.LG_003_01_KSLINES', N'DEPARTMENT') IS NOT NULL THEN ISNULL(DEPARTMENT, 0)
           ELSE DEPARTMENT
       END,
       CAPIBLOCK_MODIFIEDBY = CASE
           WHEN COL_LENGTH(N'dbo.LG_003_01_KSLINES', N'CAPIBLOCK_MODIFIEDBY') IS NOT NULL THEN 1
           ELSE CAPIBLOCK_MODIFIEDBY
       END,
       CAPIBLOCK_MODIFIEDDATE = CASE
           WHEN COL_LENGTH(N'dbo.LG_003_01_KSLINES', N'CAPIBLOCK_MODIFIEDDATE') IS NOT NULL THEN GETDATE()
           ELSE CAPIBLOCK_MODIFIEDDATE
       END,
       CAPIBLOCK_MODIFIEDHOUR = CASE
           WHEN COL_LENGTH(N'dbo.LG_003_01_KSLINES', N'CAPIBLOCK_MODIFIEDHOUR') IS NOT NULL THEN DATEPART(HOUR, GETDATE())
           ELSE CAPIBLOCK_MODIFIEDHOUR
       END,
       CAPIBLOCK_MODIFIEDMIN = CASE
           WHEN COL_LENGTH(N'dbo.LG_003_01_KSLINES', N'CAPIBLOCK_MODIFIEDMIN') IS NOT NULL THEN DATEPART(MINUTE, GETDATE())
           ELSE CAPIBLOCK_MODIFIEDMIN
       END,
       CAPIBLOCK_MODIFIEDSEC = CASE
           WHEN COL_LENGTH(N'dbo.LG_003_01_KSLINES', N'CAPIBLOCK_MODIFIEDSEC') IS NOT NULL THEN DATEPART(SECOND, GETDATE())
           ELSE CAPIBLOCK_MODIFIEDSEC
       END
FROM dbo.LG_003_01_KSLINES AS k
WHERE k.TRCODE = 11
  AND ISNULL(k.CANCELLED, 0) = 0
  AND (
      k.SIGN IS NULL
      OR k.TRCURR IS NULL
      OR ISNULL(k.TRRATE, 0) = 0
      OR ISNULL(k.TRNET, 0) = 0
      OR ISNULL(k.REPORTRATE, 0) = 0
      OR ISNULL(k.REPORTNET, 0) = 0
      OR k.ACCREF IS NULL
      OR k.CENTERREF IS NULL
      OR k.CASHACCREF IS NULL
      OR k.CASHCENREF IS NULL
      OR k.ACCFICHEREF IS NULL
      OR k.ACCOUNTED IS NULL
      OR k.REFLECTED IS NULL
      OR k.STATUS IS NULL
      OR k.AFFECTRISK IS NULL
      OR k.BRANCH IS NULL
      OR k.DEPARTMENT IS NULL
  );

DECLARE @UpdatedRows INT = @@ROWCOUNT;

COMMIT TRANSACTION;

SELECT @UpdatedRows AS repaired_cashbox_sign_rows;
