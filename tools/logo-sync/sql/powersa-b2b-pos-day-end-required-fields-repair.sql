/*
Repair existing PowerSA POS day-end Logo rows so Logo cashbox/customer totals
can read them.

This script does not create duplicate movements. It only fills required Logo
fields on rows already exported with DOCODE B2B-POSDAYEND-*.
*/

SET NOCOUNT ON;
SET XACT_ABORT ON;

IF OBJECT_ID(N'dbo.LG_003_01_KSLINES', N'U') IS NULL
OR OBJECT_ID(N'dbo.LG_003_01_CLFLINE', N'U') IS NULL
BEGIN
    RAISERROR('Required Logo movement tables were not found.', 16, 1);
    RETURN;
END;

IF OBJECT_ID(N'dbo.B2B_BACKUP_POSDAYEND_REQUIRED_FIELDS_20260827', N'U') IS NULL
BEGIN
    SELECT
        'KSLINES' AS SOURCE_TABLE,
        LOGICALREF,
        DOCODE,
        DATE_,
        SIGN,
        AMOUNT,
        TRCURR,
        TRRATE,
        TRNET,
        REPORTRATE,
        REPORTNET,
        CANCELLED,
        STATUS,
        AFFECTRISK,
        BRANCH,
        DEPARTMENT,
        DOCDATE,
        TIME_,
        GETDATE() AS BACKED_UP_AT
    INTO dbo.B2B_BACKUP_POSDAYEND_REQUIRED_FIELDS_20260827
    FROM dbo.LG_003_01_KSLINES
    WHERE DOCODE LIKE 'B2B-POSDAYEND-%';
END;

IF OBJECT_ID(N'dbo.B2B_BACKUP_POSDAYEND_CLFLINE_REQUIRED_FIELDS_20260827', N'U') IS NULL
BEGIN
    SELECT
        LOGICALREF,
        SOURCEFREF,
        DOCODE,
        DATE_,
        MODULENR,
        TRCODE,
        CLIENTREF,
        SIGN,
        AMOUNT,
        TRCURR,
        TRRATE,
        TRNET,
        REPORTRATE,
        REPORTNET,
        CANCELLED,
        STATUS,
        MONTH_,
        YEAR_,
        BRANCH,
        DEPARTMENT,
        PAIDINCASH,
        GETDATE() AS BACKED_UP_AT
    INTO dbo.B2B_BACKUP_POSDAYEND_CLFLINE_REQUIRED_FIELDS_20260827
    FROM dbo.LG_003_01_CLFLINE
    WHERE DOCODE LIKE 'B2B-POSDAYEND-%';
END;

UPDATE dbo.LG_003_01_KSLINES
SET
    SIGN = ISNULL(SIGN, 0),
    TRCURR = ISNULL(TRCURR, 0),
    TRRATE = COALESCE(NULLIF(TRRATE, 0), 1),
    TRNET = COALESCE(TRNET, AMOUNT, 0),
    REPORTRATE = COALESCE(NULLIF(REPORTRATE, 0), 1),
    REPORTNET = COALESCE(REPORTNET, AMOUNT, 0),
    CANCELLED = ISNULL(CANCELLED, 0),
    STATUS = ISNULL(STATUS, 0),
    AFFECTRISK = ISNULL(AFFECTRISK, 0),
    BRANCH = ISNULL(BRANCH, 0),
    DEPARTMENT = ISNULL(DEPARTMENT, 0),
    ACCREF = ISNULL(ACCREF, 0),
    CENTERREF = ISNULL(CENTERREF, 0),
    CASHACCREF = ISNULL(CASHACCREF, 0),
    CASHCENREF = ISNULL(CASHCENREF, 0),
    ACCFICHEREF = ISNULL(ACCFICHEREF, 0),
    ACCOUNTED = ISNULL(ACCOUNTED, 0),
    REFLECTED = ISNULL(REFLECTED, 0),
    DOCDATE = COALESCE(DOCDATE, CAPIBLOCK_MODIFIEDDATE, CAPIBLOCK_CREADEDDATE, DATE_),
    TIME_ = CASE
        WHEN ISNULL(TIME_, 0) = 0 THEN
            (ISNULL(CAPIBLOCK_MODIFIEDHOUR, ISNULL(HOUR_, 0)) * 16777216)
            + (ISNULL(CAPIBLOCK_MODIFIEDMIN, ISNULL(MINUTE_, 0)) * 65536)
            + (ISNULL(CAPIBLOCK_MODIFIEDSEC, 0) * 256)
        ELSE TIME_
    END
WHERE DOCODE LIKE 'B2B-POSDAYEND-%'
  AND (
    SIGN IS NULL
    OR TRCURR IS NULL
    OR ISNULL(TRRATE, 0) = 0
    OR TRNET IS NULL
    OR ISNULL(REPORTRATE, 0) = 0
    OR REPORTNET IS NULL
    OR CANCELLED IS NULL
    OR STATUS IS NULL
    OR AFFECTRISK IS NULL
    OR BRANCH IS NULL
    OR DEPARTMENT IS NULL
    OR ACCREF IS NULL
    OR CENTERREF IS NULL
    OR CASHACCREF IS NULL
    OR CASHCENREF IS NULL
    OR ACCFICHEREF IS NULL
    OR ACCOUNTED IS NULL
    OR REFLECTED IS NULL
    OR DOCDATE IS NULL
    OR ISNULL(TIME_, 0) = 0
  );

DECLARE @KslinesUpdated INT = @@ROWCOUNT;

UPDATE dbo.LG_003_01_CLFLINE
SET
    TRCURR = ISNULL(TRCURR, 0),
    TRRATE = COALESCE(NULLIF(TRRATE, 0), 1),
    TRNET = COALESCE(TRNET, AMOUNT, 0),
    REPORTRATE = COALESCE(NULLIF(REPORTRATE, 0), 1),
    REPORTNET = COALESCE(REPORTNET, AMOUNT, 0),
    CANCELLED = ISNULL(CANCELLED, 0),
    STATUS = ISNULL(STATUS, 0),
    MONTH_ = ISNULL(MONTH_, MONTH(DATE_)),
    YEAR_ = ISNULL(YEAR_, YEAR(DATE_)),
    BRANCH = ISNULL(BRANCH, 0),
    DEPARTMENT = ISNULL(DEPARTMENT, 0),
    PAIDINCASH = ISNULL(PAIDINCASH, 0)
WHERE DOCODE LIKE 'B2B-POSDAYEND-%'
  AND (
    TRCURR IS NULL
    OR ISNULL(TRRATE, 0) = 0
    OR TRNET IS NULL
    OR ISNULL(REPORTRATE, 0) = 0
    OR REPORTNET IS NULL
    OR CANCELLED IS NULL
    OR STATUS IS NULL
    OR MONTH_ IS NULL
    OR YEAR_ IS NULL
    OR BRANCH IS NULL
    OR DEPARTMENT IS NULL
    OR PAIDINCASH IS NULL
  );

DECLARE @ClflineUpdated INT = @@ROWCOUNT;

SELECT
    @KslinesUpdated AS repaired_pos_day_end_cashbox_rows,
    @ClflineUpdated AS repaired_pos_day_end_customer_ledger_rows;
