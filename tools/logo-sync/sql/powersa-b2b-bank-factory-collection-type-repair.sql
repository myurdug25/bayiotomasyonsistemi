/*
Repair B2B-created bank transfer and factory card collection type metadata.

Scope:
-- Bank transfer rows created from B2B HE, POSEXP, and COL references:
  - BNFLINE.TRANSTYPE 0 -> 1 so Logo shows an explicit transfer type.
  - BNFLINE.TRCODE 3/4 -> 1 so the bank slip row shows Havale instead of Belirlenmemis.
  - BNFLINE.BANKPROCTYPE/BANKPROCCODE -> 2 so the bank slip row dropdown selects Havale.
  - Linked CLFLINE.TRCODE 3/21 -> 20 so customer ledger shows incoming transfer, not Borc Dekontu or outgoing transfer.
- Factory card rows created from B2B FBC* references:
  - CLFICHE/CLFLINE.TRCODE 3/70 -> 5 so Logo shows Virman Islemi instead of Borc Dekontu or Kredi Karti Fisi.

The script does not create movements and is idempotent.
*/

SET NOCOUNT ON;
SET XACT_ABORT ON;

IF OBJECT_ID(N'dbo.LG_003_01_BNFICHE', N'U') IS NULL
OR OBJECT_ID(N'dbo.LG_003_01_BNFLINE', N'U') IS NULL
OR OBJECT_ID(N'dbo.LG_003_01_CLFICHE', N'U') IS NULL
OR OBJECT_ID(N'dbo.LG_003_01_CLFLINE', N'U') IS NULL
BEGIN
    RAISERROR('Required Logo collection tables were not found.', 16, 1);
    RETURN;
END;

IF OBJECT_ID(N'dbo.B2B_BACKUP_BANK_FACTORY_COLLECTION_TYPE_20260826', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.B2B_BACKUP_BANK_FACTORY_COLLECTION_TYPE_20260826 (
        BACKUP_ID BIGINT IDENTITY(1,1) NOT NULL PRIMARY KEY,
        TABLE_NAME SYSNAME NOT NULL,
        LOGICALREF INT NOT NULL,
        OLD_TRCODE SMALLINT NULL,
        OLD_TRANSTYPE SMALLINT NULL,
        OLD_BANKPROCTYPE SMALLINT NULL,
        OLD_BANKPROCCODE SMALLINT NULL,
        BACKED_UP_AT DATETIME2(0) NOT NULL DEFAULT SYSUTCDATETIME()
    );
END;

IF COL_LENGTH(N'dbo.B2B_BACKUP_BANK_FACTORY_COLLECTION_TYPE_20260826', N'OLD_BANKPROCTYPE') IS NULL
    ALTER TABLE dbo.B2B_BACKUP_BANK_FACTORY_COLLECTION_TYPE_20260826 ADD OLD_BANKPROCTYPE SMALLINT NULL;

IF COL_LENGTH(N'dbo.B2B_BACKUP_BANK_FACTORY_COLLECTION_TYPE_20260826', N'OLD_BANKPROCCODE') IS NULL
    ALTER TABLE dbo.B2B_BACKUP_BANK_FACTORY_COLLECTION_TYPE_20260826 ADD OLD_BANKPROCCODE SMALLINT NULL;

GO

BEGIN TRANSACTION;

INSERT INTO dbo.B2B_BACKUP_BANK_FACTORY_COLLECTION_TYPE_20260826
    (TABLE_NAME, LOGICALREF, OLD_TRCODE, OLD_TRANSTYPE, OLD_BANKPROCTYPE, OLD_BANKPROCCODE)
SELECT N'LG_003_01_BNFLINE', l.LOGICALREF, l.TRCODE, l.TRANSTYPE, l.BANKPROCTYPE, l.BANKPROCCODE
FROM dbo.LG_003_01_BNFLINE l
JOIN dbo.LG_003_01_BNFICHE f ON f.LOGICALREF = l.SOURCEFREF
WHERE ISNULL(f.CANCELLED, 0) = 0
  AND ISNULL(l.CANCELLED, 0) = 0
  AND ISNULL(l.CLIENTREF, 0) > 0
  AND ISNULL(f.TRCODE, 0) IN (3, 4)
  AND (
      ISNULL(l.TRCODE, 0) <> 1
      OR ISNULL(l.TRANSTYPE, 0) <> 1
      OR ISNULL(l.BANKPROCTYPE, 0) <> 2
      OR ISNULL(l.BANKPROCCODE, 0) <> 2
  )
  AND (
      l.LINEEXP LIKE 'HE%'
      OR f.GENEXP1 LIKE 'HE%'
      OR l.DOCODE LIKE 'HE%'
      OR f.FICHENO LIKE '%B2B%'
      OR f.GENEXP1 LIKE '%B2B%'
      OR l.TRANNO LIKE '%B2B%'
      OR l.DOCODE LIKE '%B2B%'
      OR l.LINEEXP LIKE '%B2B%'
      OR l.DOCODE LIKE 'FBC%'
      OR l.LINEEXP LIKE 'FBC%'
  )
  AND NOT EXISTS (
      SELECT 1
      FROM dbo.B2B_BACKUP_BANK_FACTORY_COLLECTION_TYPE_20260826 b
      WHERE b.TABLE_NAME = N'LG_003_01_BNFLINE'
        AND b.LOGICALREF = l.LOGICALREF
  );

UPDATE l
   SET TRANSTYPE = 1,
       TRCODE = 1,
       BANKPROCTYPE = 2,
       BANKPROCCODE = 2
FROM dbo.LG_003_01_BNFLINE l
JOIN dbo.LG_003_01_BNFICHE f ON f.LOGICALREF = l.SOURCEFREF
WHERE ISNULL(f.CANCELLED, 0) = 0
  AND ISNULL(l.CANCELLED, 0) = 0
  AND ISNULL(l.CLIENTREF, 0) > 0
  AND ISNULL(f.TRCODE, 0) IN (3, 4)
  AND (
      ISNULL(l.TRCODE, 0) <> 1
      OR ISNULL(l.TRANSTYPE, 0) <> 1
      OR ISNULL(l.BANKPROCTYPE, 0) <> 2
      OR ISNULL(l.BANKPROCCODE, 0) <> 2
  )
  AND (
      l.LINEEXP LIKE 'HE%'
      OR f.GENEXP1 LIKE 'HE%'
      OR l.DOCODE LIKE 'HE%'
      OR f.FICHENO LIKE '%B2B%'
      OR f.GENEXP1 LIKE '%B2B%'
      OR l.TRANNO LIKE '%B2B%'
      OR l.DOCODE LIKE '%B2B%'
      OR l.LINEEXP LIKE '%B2B%'
      OR l.DOCODE LIKE 'FBC%'
      OR l.LINEEXP LIKE 'FBC%'
  );

DECLARE @RepairedBankLineTypes INT = @@ROWCOUNT;

INSERT INTO dbo.B2B_BACKUP_BANK_FACTORY_COLLECTION_TYPE_20260826
    (TABLE_NAME, LOGICALREF, OLD_TRCODE, OLD_TRANSTYPE)
SELECT N'LG_003_01_CLFLINE', c.LOGICALREF, c.TRCODE, NULL
FROM dbo.LG_003_01_CLFLINE c
JOIN dbo.LG_003_01_BNFLINE l ON l.LOGICALREF = c.SOURCEFREF
JOIN dbo.LG_003_01_BNFICHE f ON f.LOGICALREF = l.SOURCEFREF
WHERE ISNULL(c.CANCELLED, 0) = 0
  AND ISNULL(f.CANCELLED, 0) = 0
  AND ISNULL(l.CANCELLED, 0) = 0
  AND ISNULL(c.MODULENR, 0) = 7
  AND ISNULL(c.TRCODE, 0) IN (3, 21)
  AND ISNULL(c.SIGN, 0) = 1
  AND (
      c.LINEEXP LIKE 'HE%'
      OR l.LINEEXP LIKE 'HE%'
      OR f.GENEXP1 LIKE 'HE%'
      OR c.DOCODE LIKE 'HE%'
  )
  AND NOT EXISTS (
      SELECT 1
      FROM dbo.B2B_BACKUP_BANK_FACTORY_COLLECTION_TYPE_20260826 b
      WHERE b.TABLE_NAME = N'LG_003_01_CLFLINE'
        AND b.LOGICALREF = c.LOGICALREF
  );

UPDATE c
   SET TRCODE = 20
FROM dbo.LG_003_01_CLFLINE c
JOIN dbo.LG_003_01_BNFLINE l ON l.LOGICALREF = c.SOURCEFREF
JOIN dbo.LG_003_01_BNFICHE f ON f.LOGICALREF = l.SOURCEFREF
WHERE ISNULL(c.CANCELLED, 0) = 0
  AND ISNULL(f.CANCELLED, 0) = 0
  AND ISNULL(l.CANCELLED, 0) = 0
  AND ISNULL(c.MODULENR, 0) = 7
  AND ISNULL(c.TRCODE, 0) IN (3, 21)
  AND ISNULL(c.SIGN, 0) = 1
  AND (
      c.LINEEXP LIKE 'HE%'
      OR l.LINEEXP LIKE 'HE%'
      OR f.GENEXP1 LIKE 'HE%'
      OR c.DOCODE LIKE 'HE%'
  );

DECLARE @RepairedBankLedgerTypes INT = @@ROWCOUNT;

INSERT INTO dbo.B2B_BACKUP_BANK_FACTORY_COLLECTION_TYPE_20260826
    (TABLE_NAME, LOGICALREF, OLD_TRCODE, OLD_TRANSTYPE)
SELECT N'LG_003_01_CLFICHE', f.LOGICALREF, f.TRCODE, NULL
FROM dbo.LG_003_01_CLFICHE f
WHERE ISNULL(f.CANCELLED, 0) = 0
  AND ISNULL(f.TRCODE, 0) IN (3, 70)
  AND (
      f.DOCODE LIKE 'FBC%'
      OR f.GENEXP1 LIKE 'FBC%'
      OR EXISTS (
          SELECT 1
          FROM dbo.LG_003_01_CLFLINE c
          WHERE c.SOURCEFREF = f.LOGICALREF
            AND (c.DOCODE LIKE 'FBC%' OR c.LINEEXP LIKE 'FBC%')
      )
  )
  AND NOT EXISTS (
      SELECT 1
      FROM dbo.B2B_BACKUP_BANK_FACTORY_COLLECTION_TYPE_20260826 b
      WHERE b.TABLE_NAME = N'LG_003_01_CLFICHE'
        AND b.LOGICALREF = f.LOGICALREF
  );

UPDATE f
   SET TRCODE = 5
FROM dbo.LG_003_01_CLFICHE f
WHERE ISNULL(f.CANCELLED, 0) = 0
  AND ISNULL(f.TRCODE, 0) IN (3, 70)
  AND (
      f.DOCODE LIKE 'FBC%'
      OR f.GENEXP1 LIKE 'FBC%'
      OR EXISTS (
          SELECT 1
          FROM dbo.LG_003_01_CLFLINE c
          WHERE c.SOURCEFREF = f.LOGICALREF
            AND (c.DOCODE LIKE 'FBC%' OR c.LINEEXP LIKE 'FBC%')
      )
  );

DECLARE @RepairedFactoryFiches INT = @@ROWCOUNT;

INSERT INTO dbo.B2B_BACKUP_BANK_FACTORY_COLLECTION_TYPE_20260826
    (TABLE_NAME, LOGICALREF, OLD_TRCODE, OLD_TRANSTYPE)
SELECT N'LG_003_01_CLFLINE', c.LOGICALREF, c.TRCODE, NULL
FROM dbo.LG_003_01_CLFLINE c
JOIN dbo.LG_003_01_CLFICHE f ON f.LOGICALREF = c.SOURCEFREF
WHERE ISNULL(c.CANCELLED, 0) = 0
  AND ISNULL(f.CANCELLED, 0) = 0
  AND ISNULL(c.MODULENR, 0) = 5
  AND ISNULL(c.TRCODE, 0) IN (3, 70)
  AND (
      c.DOCODE LIKE 'FBC%'
      OR c.LINEEXP LIKE 'FBC%'
      OR f.DOCODE LIKE 'FBC%'
      OR f.GENEXP1 LIKE 'FBC%'
  )
  AND NOT EXISTS (
      SELECT 1
      FROM dbo.B2B_BACKUP_BANK_FACTORY_COLLECTION_TYPE_20260826 b
      WHERE b.TABLE_NAME = N'LG_003_01_CLFLINE'
        AND b.LOGICALREF = c.LOGICALREF
  );

UPDATE c
   SET TRCODE = 5
FROM dbo.LG_003_01_CLFLINE c
JOIN dbo.LG_003_01_CLFICHE f ON f.LOGICALREF = c.SOURCEFREF
WHERE ISNULL(c.CANCELLED, 0) = 0
  AND ISNULL(f.CANCELLED, 0) = 0
  AND ISNULL(c.MODULENR, 0) = 5
  AND ISNULL(c.TRCODE, 0) IN (3, 70)
  AND (
      c.DOCODE LIKE 'FBC%'
      OR c.LINEEXP LIKE 'FBC%'
      OR f.DOCODE LIKE 'FBC%'
      OR f.GENEXP1 LIKE 'FBC%'
  );

DECLARE @RepairedFactoryLedgerRows INT = @@ROWCOUNT;

COMMIT TRANSACTION;

SELECT
    @RepairedBankLineTypes AS repaired_bank_line_types,
    @RepairedBankLedgerTypes AS repaired_bank_ledger_types,
    @RepairedFactoryFiches AS repaired_factory_fiches,
    @RepairedFactoryLedgerRows AS repaired_factory_ledger_rows;
